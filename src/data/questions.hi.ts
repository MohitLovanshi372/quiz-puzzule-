export const HINDI_QUESTIONS: Record<string, HindiQuestion> =
  Object.fromEntries(
    Object.entries(entries).map(
      ([id, [question, options, hint, explanation]]) => [
        id,
        { question, options, hint, explanation },
      ],
    ),
  );
export function localizeQuestion(
  question: Question,
  language: "en" | "hi",
): Question {
  return language === "hi" && HINDI_QUESTIONS[question.id]
    ? { ...question, ...HINDI_QUESTIONS[question.id] }
    : question;
}

// Review/history localizes by stable question ID, including older English records.
import { QUESTION_BANK } from "./questions";
import type { AnswerRecord } from "../types";
export function localizeAnswer(
  answer: AnswerRecord,
  language: "en" | "hi",
): AnswerRecord {
  const original = QUESTION_BANK.find(
    (question) => question.id === answer.questionId,
  );
  if (!original) return answer;
  const translated = localizeQuestion(original, language);
  return {
    ...answer,
    questionText: translated.question,
    explanation: translated.explanation,
  };
}
