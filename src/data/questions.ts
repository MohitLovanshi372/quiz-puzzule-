/**
 * Returns a randomized subset of questions filtered by category and difficulty.
 */
export function getQuizQuestions(categoryId: CategoryId, difficulty: Difficulty, count: number = 8): Question[] {
  let pool = QUESTION_BANK;

  if (categoryId !== 'all') {
    pool = pool.filter(q => q.categoryId === categoryId);
  }

  // Filter by difficulty, fallback to adjacent difficulty if needed
  let filtered = pool.filter(q => q.difficulty === difficulty);
  if (filtered.length < count) {
    // Fill remaining with other difficulties in the same category
    const remaining = pool.filter(q => q.difficulty !== difficulty);
    filtered = [...filtered, ...remaining];
  }

  // Shuffle array using Fisher-Yates
  const shuffled = [...filtered];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}

